test("Monthly 保留分隔线内的正文锚点", async () => {
	const raw = "-   09:00\n\t\n\t---\n\t\n\ttext ^inside\n\t\n\t---";
	const parser = new DiaryMemoParser();
	const observations = parser.parseRevision({ sourcePath: "Daily/2026-08-01.md", logicalDate: "2026-08-01", content: raw, sourceRevision: "daily" }).observations;
	const result = await buildMonthlyProjection({ period: "2026-08", settings: makeSettings(), observations });
	assert.ok(result.content.includes(raw));
	assert.equal(result.content.match(/\^inside/gu)?.length, 1);
});

test("Monthly 可投影带逻辑首空行的旧式 paragraph 锚点", async () => {
	const parser = new DiaryMemoParser();
	const raw = "- 09:00 \n  text ^legacy-leading-space";
	const observations = parser.parseRevision({ sourcePath: "Daily/2025-06-08.md", logicalDate: "2025-06-08", content: raw, sourceRevision: "daily" }).observations;
	const projection = await buildMonthlyProjection({ period: "2025-06", settings: makeSettings(), observations });
	assert.ok(projection.content.includes(raw));
	const after = parser.parseRevision({ sourcePath: projection.path, logicalDate: "2025-06-08", content: projection.content, sourceRevision: projection.outputHash }).observations[0];
	assert.equal(after.content, "\ntext");
	assert.equal(after.blockAnchor?.kind, "paragraph");
	assert.equal(after.existingBlockId, "legacy-leading-space");
});

test("Monthly 消费当前锚点源信息，不重复附加历史末项或移动主锚点", async () => {
	const parser = new DiaryMemoParser();
	for (const version of memoPrefixHistory) for (const sample of version.samples) for (const raw of [sample.raw, sample.anchoredRaw]) {
		const before = parser.parseRevision({ sourcePath: "Daily/2026-08-01.md", logicalDate: "2026-08-01", content: raw, sourceRevision: "daily" }).observations[0];
		const projection = await buildMonthlyProjection({ period: "2026-08", settings: makeSettings(), observations: [before] });
		const after = parser.parseRevision({ sourcePath: projection.path, logicalDate: before.logicalDate,
			content: projection.content, sourceRevision: projection.outputHash }).observations[0];
		assert.equal(after.content, sample.content, sample.name);
		assert.equal(after.existingBlockId, before.existingBlockId, sample.name);
		assert.equal(after.blockAnchor?.kind, before.blockAnchor?.kind, sample.name);
		assert.equal(after.time, before.time);
		assert.equal((projection.content.match(/\^child-anchor/gu) ?? []).length, sample.category === "20" ? 1 : 0);
	}
});

test("Monthly projection 对同一 Catalog 输入生成确定字节且只保留 Daily 已有 block ID", async () => {
	const settings = makeSettings();
	const later = makeObservation({
		observationKey: "Daily/2026-08-02.md\0a",
		sourcePath: "Daily/2026-08-02.md",
		logicalDate: "2026-08-02",
		startLine: 8,
		time: "09:30",
		content: "second\nline",
		existingBlockId: "kept-id",
	});
	const earlier = makeObservation({
		observationKey: "Daily/2026-08-01.md\0a",
		sourcePath: "Daily/2026-08-01.md",
		logicalDate: "2026-08-01",
		startLine: 2,
		time: "08:00:00",
		content: "first",
		existingBlockId: null,
	});

	const first = await buildMonthlyProjection({ period: "2026-08", settings, observations: [later, earlier] });
	const second = await buildMonthlyProjection({ period: "2026-08", settings, observations: [earlier, later] });

	assert.equal(first.content, second.content);
	// 输出规则版本与锚点源信息进入输入摘要，投影字节及 outputHash 仍保持原有固定值。
	assert.equal(first.sourceDigest, "ccc661c3d0cdf4c563898f10afd69efe667ca93596061f05fc44a6bb5cbe3a4e");
	assert.equal(first.outputHash, "45655fa980004f2c9c6bc6bae67bcccce918d3c782da0d6a67aa500fa5dd1c18");
	assert.equal(first.path, "Knomo/Memos-2026-08.md");
	assert.equal(first.content, [
		"<!-- knomo:monthly-archive -->",
		"<small>This file is automatically generated by Knomo from Daily Notes. Edits made here will not sync back to Knomo or the corresponding Daily Note.</small>",
		"# 2026-08",
		"## [[2026-08-01]]",
		"- 08:00:00 first",
		"## [[2026-08-02]]",
		"- 09:30 second\n  line ^kept-id",
		"",
	].join("\n\n").replace(/\n\n$/u, "\n"));
	assert.equal(first.content.includes("^kept-id"), true);
	assert.equal(first.content.match(/\^[\w-]+/gu)?.length, 1);
	assert.equal(first.content.includes("\r"), false);
	assert.equal(first.content.endsWith("\n"), true);
	assert.equal(first.content.endsWith("\n\n"), false);
});

test("Monthly 复用语义保真表示，正文空白和 Daily 已有引用 ID 可完整恢复", async () => {
	const parser = new DiaryMemoParser();
	for (const sample of memoMarkdownConsistencyFixtures) for (const existingBlockId of [null, "kept-id"]) {
		const projection = await buildMonthlyProjection({ period: "2026-08", settings: makeSettings(),
			observations: [makeObservation({ logicalDate: "2026-08-01", time: "08:00", content: sample.content, existingBlockId })] });
		const parsed = parser.parseRevision({ sourcePath: projection.path, logicalDate: "2026-08-01", content: projection.content, sourceRevision: projection.outputHash }).observations;
		assert.equal(parsed.length, 1, sample.name);
		assert.equal(parsed[0].content, sample.content, sample.name);
		assert.equal(parsed[0].time, "08:00");
		assert.equal(parsed[0].existingBlockId, existingBlockId, sample.name);
		assert.ok(hasKnomoMonthlyArchiveMarker(projection.content));
	}
});

test("新建 Monthly 按共享 locale 生成中英文说明", async () => {
	const chinese = await buildMonthlyProjection({
		period: "2026-08",
		settings: makeSettings("zh-cn"),
		observations: [],
	});
	const english = await buildMonthlyProjection({
		period: "2026-08",
		settings: makeSettings("en"),
		observations: [],
	});

	assert.equal(chinese.content, [
		"<!-- knomo:monthly-archive -->",
		"<small>本文件内容由 Knomo 根据日记自动生成，在此编辑不会同步到 Knomo 或对应日记中。</small>",
		"# 2026-08",
		"",
	].join("\n\n").replace(/\n\n$/u, "\n"));
	assert.match(english.content, /<small>This file is automatically generated by Knomo from Daily Notes\./u);
});

test("Monthly marker 同时识别旧多行格式和新单行格式，只保留旧格式原文", () => {
	const legacy = [
		"<!-- knomo:monthly-archive",
		"Knomo 月度归档文件：此文件根据日记自动生成。请勿直接在此编辑 memo；请在 Knomo 或对应日记中编辑。",
		"-->",
	].join("\n");
	const current = "<!-- knomo:monthly-archive -->\n\n<small>notice</small>";

	assert.equal(hasKnomoMonthlyArchiveMarker(legacy), true);
	assert.equal(hasKnomoMonthlyArchiveMarker(current), true);
	assert.equal(hasKnomoMonthlyArchiveMarker(`# title\n${current}`), false);
	assert.equal(hasKnomoMonthlyArchiveMarker("<!-- knomo:monthly-archive-copy -->"), false);
	assert.equal(extractLegacyMonthlyArchiveMarker(`${legacy}\n\n# 2026-08`), legacy);
	assert.equal(extractLegacyMonthlyArchiveMarker(current), null);
});

test("Monthly heading 只使用传入 locale，且支持相邻的完整 token", () => {
	assert.equal(normalizeMonthlyLocaleKey("zh"), "zh-cn");
	assert.equal(normalizeMonthlyLocaleKey("fr_FR"), "fr-fr");
	moment.locale("fr");
	assert.equal(
		formatMonthlyDateHeading("## D MMMM YYYY dddd", "2026-08-09", "en"),
		"## 9 August 2026 Sunday",
	);
	moment.locale("en");
	assert.equal(
		formatMonthlyDateHeading("## YYYYM MMMMM MMMMD DDdddd", "2026-08-09", "fr"),
		"## 20268 août8 août9 09dimanche",
	);
});

test("两台不同 UI 语言设备使用同一共享 locale 时生成字节级相同 Monthly", async () => {
	const observation = makeObservation({ logicalDate: "2026-08-09" });
	moment.locale("en");
	const left = await buildMonthlyProjection({
		period: "2026-08",
		settings: makeSettings("fr"),
		observations: [observation],
	});
	moment.locale("fr");
	const right = await buildMonthlyProjection({
		period: "2026-08",
		settings: makeSettings("fr"),
		observations: [observation],
	});
	moment.locale("en");

	assert.deepEqual(right.bytes, left.bytes);
	assert.equal(right.content, left.content);
	assert.match(right.content, /## \[\[2026-08-09\]\]/u);
});

test("Monthly 只维护 canonical 路径，忽略同目录或其他目录的 conflict copy", () => {
	const settings = makeSettings();
	assert.equal(getMonthlyCanonicalPeriod(settings, "Knomo/Memos-2026-08 (conflict).md"), null);
	assert.equal(getMonthlyCanonicalPeriod(settings, "Knomo/Memos-2026-08.md"), "2026-08");
	assert.equal(getMonthlyCanonicalPeriod(settings, "Elsewhere/Memos-2026-08 (conflict).md"), null);
});

function makeSettings(locale = "en"): KnomoSettings & { locale: string } {
	return {
		composerToolbar: normalizeComposerToolbar(undefined),
		settingsVersion: 4,
		dailyHeading: "## Memos",
		dailyInsertPosition: "bottom",
		memoTimeFormat: "HH:mm:ss",
		monthlyMemoFolder: "Knomo",
		monthlyMemoFileFormat: "Memos-YYYY-MM.md",
		monthlyDateHeadingFormat: "## [[YYYY-MM-DD]]",
		monthlyDateOrder: "asc",
		legacyDailyHeadings: [],
		timeBuoyEnabled: true,
		recentTimeFlowEnabled: true,
		mobileCompactMode: "auto",
		desktopSidebarWidth: 248,
		desktopSidebarCollapsed: false,
		excludeMonthlyMemosFromObsidian: true,
		pinnedTags: [],
		locale,
	};
}

function makeObservation(overrides: Partial<CatalogObservation>): CatalogObservation {
	const observation: CatalogObservation = {
		occurrenceIndex: 0,
		occurrenceCount: 1,
		observationKey: "Daily/2026-08-09.md\u00000000000001",
		createdAtKey: "2026-08-09T09:00:00",
		sourcePath: "Daily/2026-08-09.md",
		sourceRevision: "a".repeat(64),
		rawBlockHash: "fnv1a-rawblock",
		logicalDate: "2026-08-09",
		section: "## Memos",
		startLine: 1,
		endLine: 1,
		time: "09:00",
		content: "memo",
		contentHash: "fnv1a-11111111",
		existingBlockId: null,
		tags: [],
		links: [],
		images: [],
		tasks: [],
		timeBuoyDates: [],
		searchBody: ["memo"],
		searchTokens: ["memo"],
		tagKeys: [],
		linkTargets: [],
		imagePaths: [],
		explicitReferenceTargets: [],
		hasLink: 0,
		hasImage: 0,
		hasTask: 0,
		hasTimeBuoy: 0,
		...overrides,
	};
	const raw = new MarkdownBlockService().buildMemoBlockWithBlockId(observation.content, observation.time, observation.existingBlockId);
	observation.blockAnchor = new DiaryMemoParser().parseRevision({ sourcePath: observation.sourcePath, logicalDate: observation.logicalDate,
		content: raw, sourceRevision: observation.sourceRevision }).observations[0].blockAnchor;
	return observation;
}
